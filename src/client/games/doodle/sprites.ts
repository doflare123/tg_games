let atlasPromise: Promise<HTMLImageElement> | null = null;
export function loadDoodleSprites(): Promise<HTMLImageElement> {
  atlasPromise ??= new Promise<HTMLImageElement>((resolve, reject) => {
    const image = new Image();
    image.onload = () => {
      void image.decode().then(
        () => resolve(image),
        (error: unknown) => {
          atlasPromise = null;
          reject(error);
        },
      );
    };
    image.onerror = () => {
      atlasPromise = null;
      reject(new Error('Не удалось загрузить графику. Попробуй открыть игру ещё раз.'));
    };
    image.src = '/assets/doodle/kenney/jumper.png';
  });
  return atlasPromise;
}
