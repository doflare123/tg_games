import type { Piece, PieceKind } from './types.ts';

type Point = readonly [number, number];
const BASE: Record<PieceKind, readonly Point[]> = {
  I: [
    [0, 1],
    [1, 1],
    [2, 1],
    [3, 1],
  ],
  O: [
    [1, 0],
    [2, 0],
    [1, 1],
    [2, 1],
  ],
  T: [
    [1, 0],
    [0, 1],
    [1, 1],
    [2, 1],
  ],
  S: [
    [1, 0],
    [2, 0],
    [0, 1],
    [1, 1],
  ],
  Z: [
    [0, 0],
    [1, 0],
    [1, 1],
    [2, 1],
  ],
  J: [
    [0, 0],
    [0, 1],
    [1, 1],
    [2, 1],
  ],
  L: [
    [2, 0],
    [0, 1],
    [1, 1],
    [2, 1],
  ],
};
export function cells(piece: Piece): Point[] {
  return BASE[piece.kind].map(([baseX, baseY]) => {
    let x = baseX;
    let y = baseY;
    const size = piece.kind === 'I' ? 4 : 3;
    if (piece.kind !== 'O') for (let r = 0; r < piece.rotation; r++) [x, y] = [size - 1 - y, x];
    return [x + piece.x, y + piece.y];
  });
}
